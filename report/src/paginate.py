"""Two-pass build: fill the page numbers of the List of Figures and List of Tables from a real layout.

    python paginate.py ../Thesis_Report_BoB_SWH_Forecasting.docx

1. builds the report, 2. lays it out with Apple Pages and exports a PDF, 3. reads the printed page number
(the footer) of the page that carries each "Figure n.m:" / "Table n.m:" caption, 4. writes pages.json and
rebuilds. The Contents is a Word field and is regenerated by Word / Pages themselves.
"""
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import pymupdf

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from build import BLOCKS  # noqa: E402
from builder import Numbering  # noqa: E402
from refs import REFS  # noqa: E402

PY = sys.executable


def build(out: Path, pages: Path | None = None) -> None:
    cmd = [PY, str(HERE / "build.py"), str(out)] + ([str(pages)] if pages else [])
    subprocess.run(cmd, check=True, cwd=HERE)


def export_pdf(docx: Path, pdf: Path) -> None:
    script = f'''
    tell application "Pages"
      set d to open POSIX file "{docx}"
      delay 4
      export d to POSIX file "{pdf}" as PDF
      close d saving no
    end tell'''
    subprocess.run(["osascript", "-e", script], check=True, capture_output=True)


def printed_number(page) -> str | None:
    """The page number printed in the footer (arabic or roman), if any."""
    h = page.rect.height
    words = [w for w in page.get_text("words") if w[1] > 0.9 * h]
    for w in sorted(words, key=lambda w: -w[1]):
        if re.fullmatch(r"\d+|[ivxlc]+", w[4]):
            return w[4]
    return None


def main() -> None:
    out = Path(sys.argv[1]).resolve()
    labels = Numbering(BLOCKS, set(REFS)).labels
    wanted = {}
    for b in BLOCKS:
        if b[0] == "fig":
            wanted[f"Figure {labels[b[1]]}:"] = b[1]
        elif b[0] == "table":
            wanted[f"Table {labels[b[1]]}:"] = b[1]
    build(out)
    with tempfile.TemporaryDirectory() as tmp:
        pdf = Path(tmp) / "layout.pdf"
        export_pdf(out, pdf)
        doc = pymupdf.open(pdf)
        pages = {}
        for page in doc:
            text = page.get_text()
            num = printed_number(page)
            for cap, key in wanted.items():
                if key not in pages and cap in text and num and num.isdigit():
                    pages[key] = num
    missing = sorted(set(wanted.values()) - set(pages))
    pj = HERE / "pages.json"
    pj.write_text(json.dumps(pages, indent=1))
    build(out, pj)
    print(f"page numbers found for {len(pages)} of {len(wanted)} figures/tables" + (f"; missing {missing}" if missing else ""))


if __name__ == "__main__":
    main()
